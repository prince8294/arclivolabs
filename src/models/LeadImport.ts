import { HydratedDocument, Model, Schema, Types, model, models } from 'mongoose';

import {
  LEAD_DUPLICATE_POLICIES,
  LEAD_IMPORT_STATUSES,
  LEAD_DISTRIBUTION_MODES,
  type LeadImportStatus,
  type LeadDistributionMode,
  type LeadDuplicatePolicy,
} from '@/lib/constants/lead-import';
import { stripVersionKey } from '@/lib/db/schema-utils';
import { enumValues } from '@/lib/constants/enums';

/** Readable import batch code format, e.g. `IMP-0001`. */
export const IMPORT_CODE_PATTERN = /^IMP-\d{4,}$/;

/**
 * One CSV import batch — a record of what was uploaded, how it was mapped,
 * how many rows passed/failed, and how the resulting leads were assigned.
 */
export interface ILeadImport {
  _id: Types.ObjectId;
  importCode: string;
  /** Idempotency key generated by the client (UUID). Must be unique. */
  requestId: string;
  fileName: string;
  fileSizeBytes: number;
  /** Optional: which CSV column mapped to which lead field. */
  columnMapping?: Record<string, string | null>;
  totalRows: number;
  validRows: number;
  warningRows: number;
  invalidRows: number;
  duplicateRows: number;
  importedRows: number;
  skippedDuplicateRows: number;
  status: LeadImportStatus;
  /** Human-readable error when status = FAILED. */
  errorMessage?: string | null;
  /** Default status assigned to all imported leads. */
  defaultStatus: string;
  /** How the imported leads were distributed. */
  distributionMode: LeadDistributionMode;
  /** Duplicate handling chosen at commit time. */
  duplicatePolicy: LeadDuplicatePolicy;
  /** Single user when mode = SINGLE_USER. */
  defaultAssignedTo?: Types.ObjectId | null;
  /** All participating users when mode = ROUND_ROBIN or SINGLE_USER. */
  assignedUserIds: Types.ObjectId[];
  createdBy: Types.ObjectId;
  completedAt?: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export type LeadImportDocument = HydratedDocument<ILeadImport>;
export type LeadImportModel = Model<ILeadImport>;

export const LeadImportSchema = new Schema<ILeadImport>(
  {
    importCode: {
      type: String,
      required: true,
      uppercase: true,
      trim: true,
      maxlength: 20,
      validate: {
        validator: (value: string) => IMPORT_CODE_PATTERN.test(value.toUpperCase()),
        message: 'importCode must follow the IMP-0000 format (e.g. IMP-0001)',
      },
    },
    requestId: {
      type: String,
      required: true,
      trim: true,
      maxlength: 64,
      unique: true,
    },
    fileName: {
      type: String,
      required: true,
      trim: true,
      maxlength: 255,
    },
    fileSizeBytes: {
      type: Number,
      required: true,
      min: 0,
    },
    columnMapping: {
      type: Schema.Types.Mixed,
      default: undefined,
    },
    totalRows: {
      type: Number,
      required: true,
      min: 0,
    },
    validRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    warningRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    invalidRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    duplicateRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    importedRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    skippedDuplicateRows: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },
    status: {
      type: String,
      required: true,
      enum: enumValues(LEAD_IMPORT_STATUSES),
      default: LEAD_IMPORT_STATUSES.PENDING,
    },
    errorMessage: {
      type: String,
      trim: true,
      maxlength: 1000,
    },
    defaultStatus: {
      type: String,
      required: true,
      trim: true,
      maxlength: 20,
    },
    distributionMode: {
      type: String,
      required: true,
      enum: enumValues(LEAD_DISTRIBUTION_MODES),
    },
    duplicatePolicy: {
      type: String,
      required: true,
      enum: enumValues(LEAD_DUPLICATE_POLICIES),
      default: LEAD_DUPLICATE_POLICIES.SKIP,
    },
    defaultAssignedTo: {
      type: Schema.Types.ObjectId,
      ref: 'User',
    },
    assignedUserIds: {
      type: [Schema.Types.ObjectId],
      ref: 'User',
      default: [],
    },
    createdBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    completedAt: {
      type: Date,
    },
  },
  {
    timestamps: true,
    collection: 'lead_imports',
    toJSON: { virtuals: false, transform: stripVersionKey },
    toObject: { virtuals: false, transform: stripVersionKey },
  }
);

LeadImportSchema.index({ importCode: 1 }, { unique: true });
LeadImportSchema.index({ status: 1, createdAt: -1 });
LeadImportSchema.index({ createdBy: 1, createdAt: -1 });
LeadImportSchema.index({ createdAt: -1 });

export const LeadImport = (models.LeadImport as Model<ILeadImport>) || model<ILeadImport>('LeadImport', LeadImportSchema);
